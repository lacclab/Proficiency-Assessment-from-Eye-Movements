# ── LEAP-Q normalization lookup maps ──────────────────────────────────────────

def _merge_file_rename_maps(
    base_rename_maps: dict[str, dict[str, str]],
    override_rename_maps: dict[str, dict[str, str]] | None = None,
) -> dict[str, dict[str, str]]:
    """Creates merged per-file rename maps, with overrides merged into base per-file dicts."""
    merged = {filename: dict(rename_map) for filename, rename_map in base_rename_maps.items()}
    for filename, extra in (override_rename_maps or {}).items():
        merged.setdefault(filename, {}).update(extra)
    return merged


